                  <p>A Main Board IPO is reserved for large, established companies — under the standard profitability route, net tangible assets must be at least ₹3 crore in each of the last three years, with average operating profit of at least ₹15 crore in three of the last five years, and net worth exceeding ₹10 crore in each of the preceding three years.</p><p>Companies that don't meet this profitability threshold can still list via the book-building QIB route, which requires allocating at least 75% of the net issue to Qualified Institutional Buyers, whose participation itself signals institutional confidence in the offer.</p><p>The process runs through a SEBI-registered merchant banker: DRHP filing with SEBI, a formal review and observation cycle, price-band finalisation, book-building and subscription, followed by allotment and listing on NSE and BSE.</p>
